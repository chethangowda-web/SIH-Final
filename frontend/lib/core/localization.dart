// UI Component: Clean, responsive Language Selector Segmented Widget
class LanguageSelectorWidget extends StatelessWidget {
  final bool isCompact;
  final Color? backgroundColor;
  final bool isLight;

  const LanguageSelectorWidget({
    super.key,
    this.isCompact = false,
    this.backgroundColor,
    this.isLight = false,
  });

  @override
  Widget build(BuildContext context) {
    return AnimatedBuilder(
      animation: LanguageController.instance,
      builder: (context, _) {
        final current = LanguageController.instance.currentLanguage;
        final lightMode = isLight || backgroundColor != null;

        return Container(
          padding: const EdgeInsets.symmetric(horizontal: 4, vertical: 3),
          decoration: BoxDecoration(
            color: backgroundColor ??
                (lightMode ? const Color(0xFFF1F5F9) : Colors.white.withValues(alpha: 0.15)),
            borderRadius: BorderRadius.circular(20),
            border: Border.all(
              color: lightMode
                  ? const Color(0xFFCBD5E1)
                  : Colors.white.withValues(alpha: 0.25),
              width: 1.2,
            ),
            boxShadow: lightMode
                ? const [
                    BoxShadow(
                      color: Color(0x0A000000),
                      blurRadius: 4,
                      offset: Offset(0, 1),
                    )
                  ]
                : null,
          ),
          child: Row(
            mainAxisSize: MainAxisSize.min,
            children: [
              Padding(
                padding: const EdgeInsets.symmetric(horizontal: 6),
                child: Icon(
                  Icons.translate_rounded,
                  size: isCompact ? 13 : 15,
                  color: lightMode ? AppConstants.primaryNavy : Colors.white,
                ),
              ),
              ...AppLanguage.values.map((lang) {
                final isSelected = lang == current;
                return MouseRegion(
                  cursor: SystemMouseCursors.click,
                  child: GestureDetector(
                    behavior: HitTestBehavior.opaque,
                    onTap: () {
                      LanguageController.instance.setLanguage(lang);
                    },
                    child: AnimatedContainer(
                      duration: const Duration(milliseconds: 150),
                      padding: EdgeInsets.symmetric(
                        horizontal: isCompact ? 9 : 12,
                        vertical: isCompact ? 4 : 6,
                      ),
                      decoration: BoxDecoration(
                        color: isSelected
                            ? (lightMode ? AppConstants.primaryNavy : Colors.white)
                            : Colors.transparent,
                        borderRadius: BorderRadius.circular(16),
                        boxShadow: isSelected && lightMode
                            ? const [
                                BoxShadow(
                                  color: Color(0x220F2942),
                                  blurRadius: 4,
                                  offset: Offset(0, 1),
                                ),
                              ]
                            : null,
                      ),
                      child: Text(
                        lang.nativeName,
                        style: TextStyle(
                          fontSize: isCompact ? 11.5 : 12.5,
                          fontWeight:
                              isSelected ? FontWeight.w800 : FontWeight.w600,
                          color: isSelected
                              ? (lightMode ? Colors.white : AppConstants.primaryNavy)
                              : (lightMode
                                  ? const Color(0xFF1E293B)
                                  : Colors.white.withValues(alpha: 0.9)),
                        ),
                      ),
                    ),
                  ),
                );
              }),
            ],
          ),
        );
      },
    );
  }
}
